package com.vlad230596.sesame.ui.theme

import androidx.compose.ui.unit.dp

/**
 * Размеры макета. Держатся в одном месте, чтобы экраны, написанные по
 * отдельности, не разъезжались по ритму.
 *
 * Кнопки открытия намеренно очень крупные и стоят внизу экрана: ТЗ §4.1 требует
 * попадания одним тапом за рулём, а низ экрана — единственное место, куда
 * большой палец дотягивается не перехватывая телефон.
 */
object Dimens {
    val SpaceXs = 4.dp
    val SpaceS = 8.dp
    val SpaceM = 16.dp
    val SpaceL = 24.dp
    val SpaceXl = 32.dp

    /** Шаг между блоками на главном экране (макет: 12). */
    val StackGap = 12.dp

    /** Высота кнопки открытия шлагбаума. */
    val BarrierButtonHeight = 146.dp

    /**
     * Высота строки «Интенсивная запись».
     *
     * Это строка, а не кнопка: на макете запись стоит под кнопками шлагбаумов
     * тонкой полосой с цветной точкой. Спутать её с открытием нельзя ни по
     * размеру, ни по цвету — а именно это и было главной опасностью крупной
     * заливной кнопки рядом.
     */
    val RecordButtonHeight = 64.dp

    /** Высота кнопки открытия внутри экрана идущей записи (макет: 104). */
    val BarrierButtonHeightCompact = 104.dp

    /** Плитка выбора метки сессии. */
    val LabelTileHeight = 172.dp

    /** Нижняя навигация. */
    val NavBarHeight = 76.dp

    /** Минимальная цель для любого второстепенного тапа. */
    val MinTouchTarget = 48.dp

    /** Скругление карточки и плашки. */
    val CardCorner = 18.dp

    /** Скругление крупного блока: карточка сессии, плитка метки. */
    val ButtonCorner = 22.dp

    /** Скругление кнопки шлагбаума. */
    val BarrierCorner = 26.dp

    /** Скругление строки-кнопки. */
    val RowCorner = 20.dp

    /** Толщина границы карточки. */
    val HairlineWidth = 1.dp

    /** Толщина границы у того, что можно нажать. */
    val BorderWidth = 1.5.dp

    /** Тонкая полоса прогресса в карточке статуса. */
    val ProgressThin = 4.dp

    /** Полоса прогресса идущей сессии. */
    val ProgressThick = 5.dp

    /** Точка состояния: зелёная «сбор жив», красная «идёт запись». */
    val DotSmall = 8.dp
    val DotMedium = 9.dp
    val DotLarge = 12.dp

    /** Иконка стрелы шлагбаума на кнопке. */
    val BarrierIcon = 40.dp

    /** Та же иконка в компактной кнопке и в виджете. */
    val BarrierIconSmall = 32.dp

    val NavIcon = 22.dp

    /** Кольцо отсчёта перед звонком. */
    val CountdownRing = 248.dp
    val CountdownRingStroke = 10.dp

    val ScreenPadding = 20.dp
}
